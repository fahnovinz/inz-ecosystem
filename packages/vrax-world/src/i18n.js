export const DICTS = { en: EN, id: ID };

let current = 'en';
export function setLang(lang) { current = DICTS[lang] ? lang : 'en'; }
export function getLang() { return current; }

export function t(key, params = {}, lang = current) {
  const dict = DICTS[lang] || EN;
  let s = dict[key] ?? EN[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (params[k] !== undefined ? params[k] : `{${k}}`));
}

export function formatClock(clock) {
  const m = Math.floor(((clock % 1440) + 1440) % 1440);
  return `${String(Math.floor(m / 60)).padStart(2, '0')}:${String(m % 60).padStart(2, '0')}`;
}

export function formatLevel(level, lang = current) {
  if (Math.abs(level) < 0.005) return lang === 'id' ? 'normal' : 'normal';
  const sign = level > 0 ? '+' : '−';
  const v = Math.abs(level);
  const s = v < 1 ? `${Math.round(v * 100)} cm` : `${v.toFixed(v % 1 ? 1 : 0)} m`;
  return `${sign}${lang === 'id' ? s.replace('.', ',') : s}`;
}
